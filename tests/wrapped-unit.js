'use strict';
const assert=require('node:assert/strict');
const E=require('../src/wrapped/engine.js');
const p=(k,d='2026-11-28',n=0)=>E.period(k,d,n);
assert.equal(p('day').start,'2026-11-27');
assert.equal(p('week').start,'2026-11-16');assert.equal(p('week').end,'2026-11-22');
assert.equal(p('month','2026-01-01').start,'2025-12-01');
assert.equal(p('quarter').end,'2026-09-30');
assert.equal(p('year').start,'2025-01-01');
assert.equal(p('month','2024-03-01').end,'2024-02-29');
assert.equal(p('month','2026-11-28',1).start,'2026-09-01');
assert.equal(E.story(p('day'),{count:0}).length,1);
assert.equal(E.story(p('day'),{unavailable:true}).length,1);
const a={count:1,income:100,expense:40,net:60,byCategory:{Comida:40}},b={count:1,net:50};
assert.equal(E.story(p('day'),a,b).length,7);
assert.equal(new Set(E.kinds.map(k=>E.story(p(k),a,b)[0].title)).size,5);
assert.throws(()=>p('week','2026-02-31'));
const s=x=>E.schedule(new Date(x));
assert.equal(s('2026-11-28T11:59:59Z').fresh.length,0);
assert.equal(s('2026-11-28T12:00:00Z').fresh[0].p.end,'2026-11-27');
assert.deepEqual(s('2026-11-30T12:00:00Z').fresh.map(x=>x.kind),['week','day']);
assert.deepEqual(s('2027-01-01T12:00:00Z').fresh.map(x=>x.kind),['year','quarter','month','day']);
assert.equal(s('2027-01-01T11:59:59Z').items.find(x=>x.kind==='year').p.end,'2025-12-31');
assert.equal(s('2027-01-01T11:59:59Z').next.kind,'year');
console.log('OK Wrapped: horarios, historias, períodos cerrados y datos insuficientes.');

assert.deepEqual(E.story(p('day'),a,b).map(x=>x.scene),['cover','income','expense','balance','category','comparison','final']);
assert.deepEqual(E.story(p('day'),a,b).find(x=>x.scene==='comparison').data,{previous:50,current:60});
assert.equal(E.story(p('day'),{count:0})[0].scene,'empty');
assert.equal(E.story(p('day'),a,b).find(x=>x.scene==='category').data.items[0][1],40);

const anchor='2026-11-30';
assert.equal(E.containing('week',anchor,'2026-11-23').end,'2026-11-29');
assert.equal(E.containing('month',anchor,'2024-02-29').start,'2024-02-01');
assert.equal(E.containing('day',anchor,anchor),null);
assert.equal(E.containing('day',anchor,'2026-02-31'),null);
const milestone={date:'2026-11-22',title:'Cuenta · Viaje'};
assert.equal(E.story(p('day'),{count:0},null,[milestone])[0].date,milestone.date);
assert.equal(E.story(p('week'),a,b,[milestone]).find(s=>s.scene==='milestone').data.events[0],milestone);

const annual=p('year','2027-01-02');
const quarters=E.chapters(annual);
assert.equal(quarters.length,4);
assert.equal(quarters[0].start,annual.start);
assert.equal(quarters.at(-1).end,annual.end);
const arc=E.story(annual,a,b,[],quarters.map((q,i)=>({...q,count:2,net:(i-2)*500}))).find(s=>s.scene==='arc');
assert.deepEqual(arc.data.items.map(x=>x[1]),[-1000,-500,0,500]);
assert.match(E.story(p('day'),{...a,estimatedFx:true},b).find(s=>s.scene==='income').detail,/se estimó con la tasa configurada/);

const intelligence=require('../src/intelligence/engine');
const payoff={kind:'payoff',id:'loan',date:'2026-11-27',title:'Capital liquidado',currency:'DOP',principal:90000,months:6};
assert.deepEqual(intelligence.originalEvents([payoff,{...payoff,id:'trivial',principal:20},{...payoff,id:'short',months:5},{...payoff,id:'opening',kind:'opening'}]),[payoff]);
assert.equal(E.specialStory(payoff)[1].date,payoff.date);
const observed={income:8000,expense:7000,net:1000,count:8,byCategory:{Comida:4000}};
const earlier={income:7800,expense:3500,net:4300,count:9,byCategory:{Comida:2000}};
const week=p('week');
const scenario=intelligence.originalScenario(week,observed,earlier);
assert.equal(scenario.result,3000);
assert.equal(intelligence.originalScenario(week,{...observed,estimatedFx:true},earlier),null);
assert.equal(intelligence.originalScenario(p('month'),observed,earlier),null);
const original=E.story(week,observed,earlier,[],[],{scenario});
assert.equal(original[0].title,'El cambio detrás de Comida');
assert.equal(original.find(s=>s.scene==='whatif').data.current,3000);
assert.equal(E.story(week,{...observed,income:0},earlier,[],[],{}).some(s=>s.scene==='income'),false);
