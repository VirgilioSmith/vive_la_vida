'use strict';
/* Vive: abrir, siguiente, anterior, guardar, tema, guardadas, Esc, y almacenamiento dañado. */
const { chromium } = require('playwright');
const open = require('../harness.js');
let ok = 0; const fallos = [];
const afirmar = (n, c, d = '') => { if (c) ok++; else fallos.push(n + (d ? ' → ' + d : '')); };
(async () => {
  process.env.TOUCH = '1';
  const b = await chromium.launch();
  const { p } = await open(b, 390, 844);
  const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  const txt = () => p.evaluate(() => document.querySelector('.vive-reader-copy')?.innerText || '');
  const cat = () => p.evaluate(() => document.querySelector('.vive-reader-category')?.textContent || '');
  const clic = (s) => p.evaluate((s) => document.querySelector(s)?.click(), s);
  await p.evaluate(() => { localStorage.setItem('vive.favs.v1', '{{{'); localStorage.setItem('vive.seen.v2', 'xx'); });
  await clic('[data-vive-open]'); await p.waitForTimeout(400);
  const t1 = await txt();
  afirmar('abre con un texto (aun con almacenamiento dañado)', t1.length > 20);
  afirmar('«Anterior» está desactivado en el primero', await p.evaluate(() => document.querySelector('[data-vive-prev]').disabled));
  await clic('[data-vive-next]'); await p.waitForTimeout(150);
  const t2 = await txt();
  afirmar('«Otro instante» cambia el texto', t2 !== t1);
  await clic('[data-vive-prev]'); await p.waitForTimeout(150);
  afirmar('«Anterior» vuelve al texto previo', (await txt()) === t1);
  await clic('[data-vive-fav]'); await p.waitForTimeout(100);
  afirmar('«Guardar» persiste', await p.evaluate(() => JSON.parse(localStorage.getItem('vive.favs.v1') || '[]').length === 1));
  await clic('[data-vive-theme="fe"]'); await p.waitForTimeout(200);
  let todoFe = (await cat()) === 'Fe';
  for (let i = 0; i < 8 && todoFe; i++) { await clic('[data-vive-next]'); await p.waitForTimeout(80); todoFe = (await cat()) === 'Fe'; }
  afirmar('el tema Fe solo muestra textos de Fe', todoFe);
  await clic('[data-vive-saved]'); await p.waitForTimeout(150);
  afirmar('«Guardadas» lista el texto guardado', (await p.evaluate(() => document.querySelector('.vive-saved-list')?.innerText || '')).includes(t1.slice(0, 20)));
  await clic('[data-vive-unsave]'); await p.waitForTimeout(150);
  afirmar('«Quitar» elimina de guardadas', await p.evaluate(() => JSON.parse(localStorage.getItem('vive.favs.v1') || '[]').length === 0));
  await p.keyboard.press('Escape'); await p.waitForTimeout(150);
  afirmar('Esc cierra', !(await p.evaluate(() => !!document.getElementById('vive-reader'))));
  afirmar('sin errores de consola', errs.length === 0, errs.join(' | '));
  await b.close();
  console.log(`vive: ${ok} correctas, ${fallos.length} fallan`); fallos.forEach((f) => console.log(' -', f));
  process.exit(fallos.length ? 1 : 0);
})();
